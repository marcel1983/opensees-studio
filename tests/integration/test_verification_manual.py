"""The Verification Manual: every case within tolerance, and the file up to date.

``docs/verification-manual.md`` is generated by ``tools/verification_manual.py``
from real runs. This test reruns them: a case outside its tolerance fails here,
and so does a manual that no longer matches what the code produces (regenerate
it with ``python tools/verification_manual.py --write``).
"""

from __future__ import annotations

import pytest

pytest.importorskip("openseespy")

from tools import verification_manual as manual


@pytest.fixture(scope="module")
def outcomes() -> list[manual.Outcome]:
    return manual.run_all()


@pytest.mark.parametrize("case", manual.CASES, ids=[case.key for case in manual.CASES])
def test_case_is_within_tolerance(case: manual.Case, outcomes: list[manual.Outcome]) -> None:
    outcome = next(o for o in outcomes if o.case is case)
    assert not outcome.error, outcome.error
    failed = [
        f"{c.quantity}: {c.computed:.6g} vs {c.reference:.6g} ({c.error:.2e} > {c.tolerance:.0e})"
        for c in outcome.checks
        if not c.passed
    ]
    assert not failed, "; ".join(failed)


def test_the_manual_is_up_to_date(outcomes: list[manual.Outcome]) -> None:
    expected = manual.render(outcomes)
    current = manual.MANUAL.read_text(encoding="utf-8")
    assert current == expected, (
        "docs/verification-manual.md is out of date: run "
        "`python tools/verification_manual.py --write`."
    )


def test_case_keys_are_unique() -> None:
    keys = [case.key for case in manual.CASES]
    assert len(keys) == len(set(keys))
